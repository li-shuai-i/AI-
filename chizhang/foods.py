def _build() -> list[dict]:
    foods: list[dict] = []
    seen: set[str] = set()
    for group in (STAPLES, MEAT, SEAFOOD, SOY_DAIRY, VEGETABLES, FRUITS,
                  NUTS, DISHES, DRINKS_SNACKS, FATS):
        for item in group:
            if item["name"] in seen:  # guard against accidental duplicates
                continue
            seen.add(item["name"])
            foods.append(item)
    for index, item in enumerate(foods):
        item["id"] = f"f{index:03d}"
    return foods


FOODS: list[dict] = _build()
BY_ID: dict[str, dict] = {f["id"]: f for f in FOODS}


def scale(food: dict, grams: float) -> dict:
    """Nutrition for an arbitrary weight of one food."""
    factor = grams / 100.0
    return {
        "kcal": round(food["per100"]["kcal"] * factor, 1),
        "protein": round(food["per100"]["protein"] * factor, 1),
        "carb": round(food["per100"]["carb"] * factor, 1),
        "fat": round(food["per100"]["fat"] * factor, 1),
    }


def _haystack(food: dict) -> str:
    return " ".join([food["name"], *food["alias"], food["category"]]).lower()


_INDEX = [(food, _haystack(food)) for food in FOODS]


def search(query: str = "", category: str = "", limit: int = 24) -> list[dict]:
    """Substring search over names, aliases and categories.

    Results are ordered so that exact and prefix matches on the primary name
    come first — typing "米" should surface 米饭 before 玉米.
    """
    q = query.strip().lower()
    pool = FOODS if not category else [f for f in FOODS if f["category"] == category]
    if not q:
        return pool[:limit]

    scored: list[tuple[int, int, dict]] = []
    for position, (food, hay) in enumerate(_INDEX):
        if category and food["category"] != category:
            continue
        name = food["name"].lower()
        if q not in hay:
            continue
        if name == q:
            score = 0
        elif name.startswith(q):
            score = 1
        elif any(q in alias.lower() for alias in food["alias"]):
            score = 2
        elif q in name:
            score = 3
        else:
            score = 4
        scored.append((score, position, food))

    scored.sort(key=lambda row: (row[0], row[1]))
    return [food for _, _, food in scored[:limit]]


def stats() -> dict:
    """Summary used by the CLI banner and the health endpoint."""
    by_cat: dict[str, int] = {}
    for food in FOODS:
        by_cat[food["category"]] = by_cat.get(food["category"], 0) + 1
    return {"total": len(FOODS), "categories": by_cat}
